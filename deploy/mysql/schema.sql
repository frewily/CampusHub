    level TINYINT UNSIGNED NULL DEFAULT 0 COMMENT '会员级别',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (user_id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE tb_voucher (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    shop_id BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '商铺id',
    title VARCHAR(255) NOT NULL COMMENT '代金券标题',
    sub_title VARCHAR(255) NULL DEFAULT NULL COMMENT '副标题',
    rules VARCHAR(1024) NULL DEFAULT NULL COMMENT '使用规则',
    pay_value BIGINT UNSIGNED NOT NULL COMMENT '支付金额，单位分',
    actual_value BIGINT NOT NULL COMMENT '抵扣金额，单位分',
    type TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0普通券，1秒杀券',
    status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '1上架，2下架，3过期',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE tb_voucher_order (
    id BIGINT NOT NULL COMMENT '主键',
    user_id BIGINT UNSIGNED NOT NULL COMMENT '下单用户id',
    voucher_id BIGINT UNSIGNED NOT NULL COMMENT '优惠券id',
    pay_type TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '支付方式',
    status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '订单状态',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '下单时间',
    pay_time TIMESTAMP NULL DEFAULT NULL COMMENT '支付时间',
    use_time TIMESTAMP NULL DEFAULT NULL COMMENT '核销时间',
    refund_time TIMESTAMP NULL DEFAULT NULL COMMENT '退款时间',
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci;
